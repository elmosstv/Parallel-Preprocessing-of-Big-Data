#!/bin/bash

# ==============================================================================
# ΡΥΘΜΙΣΕΙΣ ΕΛΕΓΧΟΥ (Πρέπει να ταιριάζουν με τα πειράματα που μόλις έτρεξες!)
# ==============================================================================
DATASET="data_1M_32.bin"
N=1000000
D=32
MODE="standard"

echo "=== Έναρξη Επαλήθευσης Ορθότητας (Verification) ==="
echo "Dataset: $DATASET (N=$N, D=$D, Mode=$MODE)"
echo "==================================================="
echo ""

# Λίστα με τα ονόματα των υλοποιήσεων
IMPLEMENTATIONS=("serial" "simd" "omp" "mpi" "cuda")

for impl in "${IMPLEMENTATIONS[@]}"; do
    # Φτιάχνουμε το όνομα του αρχείου εξόδου με βάση το N και το D (όπως στο προηγούμενο script)
    OUTPUT_FILE="out_${impl}.bin"

    # Ελέγχουμε αν το αρχείο υπάρχει
    if [ -f "$OUTPUT_FILE" ]; then
        echo "------------------------------------------------"
        echo "Ελέγχεται η υλοποίηση: [ $impl ]"
        echo "Αρχείο C++ Output  : $OUTPUT_FILE"
        echo "------------------------------------------------"
        
        python3 scripts/verify_scaler.py \
            --input $DATASET \
            --cpp-output $OUTPUT_FILE \
            --samples $N \
            --features $D \
            --mode $MODE
        
        echo ""
    else
        echo " Το αρχείο $OUTPUT_FILE δεν βρέθηκε."
        echo " Η υλοποίηση '$impl' μάλλον δεν εκτελέστηκε ή το όνομα είναι διαφορετικό."
        echo ""
    fi
done

echo "==================================================="
echo "Ο μαζικός έλεγχος ολοκληρώθηκε!"